def test_update_password_me(
    client: TestClient, superuser_token_headers: dict[str, str], db: MongoClient
) -> None:
    database = db[settings.MONGODB_DB]
    new_password = random_lower_string()
    data = {
        "current_password": settings.FIRST_SUPERUSER_PASSWORD,
        "new_password": new_password,
    }
    r = client.patch(
        f"{settings.API_V1_STR}/users/me/password",
        headers=superuser_token_headers,
        json=data,
    )
    assert r.status_code == 200
    updated_user = r.json()
    assert updated_user["message"] == "Password updated successfully"

    user_doc = database.users.find_one({"email": settings.FIRST_SUPERUSER})
    assert user_doc
    assert user_doc["email"] == settings.FIRST_SUPERUSER
    verified, _ = verify_password(new_password, user_doc["hashed_password"])
    assert verified

    # Revert to the old password to keep consistency in test
    old_data = {
        "current_password": new_password,
        "new_password": settings.FIRST_SUPERUSER_PASSWORD,
    }
    r = client.patch(
        f"{settings.API_V1_STR}/users/me/password",
        headers=superuser_token_headers,
        json=old_data,
    )

    assert r.status_code == 200
    user_doc = database.users.find_one({"email": settings.FIRST_SUPERUSER})
    assert user_doc
    verified, _ = verify_password(
        settings.FIRST_SUPERUSER_PASSWORD, user_doc["hashed_password"]
    )
    assert verified


