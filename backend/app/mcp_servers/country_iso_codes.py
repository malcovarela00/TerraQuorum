def resolve_iso_numeric(country_name: str) -> str | None:
    """Look up the ISO 3166-1 numeric code for a country name (Spanish)."""
    code = COUNTRY_NAME_TO_ISO_NUMERIC.get(country_name)
    if code:
        return code
    for key, value in COUNTRY_NAME_TO_ISO_NUMERIC.items():
        if key.casefold() == country_name.casefold():
            return value
    return None
